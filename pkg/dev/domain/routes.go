package domain

import (
	"fmt"
	"sort"
	"strings"

	portsdomain "github.com/manovaspace/orbit-cli/pkg/ports/domain"
)

// routesRuns is the registry runs value that a native dev process has.
const routesRuns = "mac"

// caddyfileHeader marks the generated Caddyfile so nobody edits it by hand.
const caddyfileHeader = "# Generated by orbit dev routes from handbook/agents/workspace/ports.yaml; do not edit."

// Route maps one native dev process to a local hostname. Name is the registry
// localhost label, URL the http://<name>.localhost address, Service the
// registry service name.
type Route struct {
	Name    string `json:"name"`
	URL     string `json:"url"`
	Port    int    `json:"port"`
	Service string `json:"service"`
}

// Routes lists the registry services with runs mac and a localhost name,
// sorted by service name.
func Routes(reg *portsdomain.Registry) []Route {
	out := []Route{}
	for _, s := range reg.Services {
		if s.Runs != routesRuns || s.Localhost == "" {
			continue
		}
		out = append(out, Route{
			Name:    s.Localhost,
			URL:     fmt.Sprintf("http://%s.localhost", s.Localhost),
			Port:    s.Port,
			Service: s.Name,
		})
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].Service != out[j].Service {
			return out[i].Service < out[j].Service
		}
		return out[i].Port < out[j].Port
	})
	return out
}

// Caddyfile renders the routes as a Caddyfile: the generated header, then one
// site block per route, separated by blank lines.
func Caddyfile(routes []Route) string {
	var b strings.Builder
	b.WriteString(caddyfileHeader)
	b.WriteString("\n")
	for _, r := range routes {
		fmt.Fprintf(&b, "\n%s {\n\treverse_proxy 127.0.0.1:%d\n}\n", r.URL, r.Port)
	}
	return b.String()
}
