package domain

import (
	"reflect"
	"testing"

	portsdomain "github.com/manovaspace/orbit-cli/pkg/ports/domain"
)

func routesRegistry() *portsdomain.Registry {
	return &portsdomain.Registry{
		Services: []portsdomain.Service{
			{Port: 10101, Name: "api", Runs: "mac", Localhost: "falak-api"},
			{Port: 10001, Name: "orbit-api-gateway", Runs: "mac", Localhost: "gateway"},
			{Port: 10027, Name: "storybook", Runs: "mac"},
			{Port: 10000, Name: "postgres", Runs: "shared"},
			{Port: 10030, Name: "handbook", Runs: "mac", Localhost: "handbook"},
		},
	}
}

func TestRoutesSelectsMacWithLocalhostSortedByService(t *testing.T) {
	got := Routes(routesRegistry())
	want := []Route{
		{Name: "falak-api", URL: "http://falak-api.localhost", Port: 10101, Service: "api"},
		{Name: "handbook", URL: "http://handbook.localhost", Port: 10030, Service: "handbook"},
		{Name: "gateway", URL: "http://gateway.localhost", Port: 10001, Service: "orbit-api-gateway"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("Routes = %+v\nwant %+v", got, want)
	}
}

func TestRoutesEmptyIsNotNil(t *testing.T) {
	got := Routes(&portsdomain.Registry{})
	if got == nil || len(got) != 0 {
		t.Fatalf("Routes(empty) = %#v, want empty non-nil slice (JSON [])", got)
	}
}

func TestCaddyfileText(t *testing.T) {
	routes := []Route{
		{Name: "gateway", URL: "http://gateway.localhost", Port: 10001, Service: "orbit-api-gateway"},
		{Name: "handbook", URL: "http://handbook.localhost", Port: 10030, Service: "handbook"},
	}
	want := "# Generated by orbit dev routes from handbook/agents/workspace/ports.yaml; do not edit.\n" +
		"\n" +
		"http://gateway.localhost {\n\treverse_proxy 127.0.0.1:10001\n}\n" +
		"\n" +
		"http://handbook.localhost {\n\treverse_proxy 127.0.0.1:10030\n}\n"
	if got := Caddyfile(routes); got != want {
		t.Fatalf("Caddyfile =\n%q\nwant\n%q", got, want)
	}
}

func TestCaddyfileWithoutRoutesHasHeaderOnly(t *testing.T) {
	want := "# Generated by orbit dev routes from handbook/agents/workspace/ports.yaml; do not edit.\n"
	if got := Caddyfile(nil); got != want {
		t.Fatalf("Caddyfile(nil) = %q", got)
	}
}
