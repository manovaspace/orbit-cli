package root

import (
	"context"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/manovaspace/orbit-cli/pkg/clierr"
	"github.com/manovaspace/orbit-cli/pkg/setup/engine"
)

// goWorkMarker is the first line of every go.work this part writes. A go.work without it is hand-made.
const goWorkMarker = "// generated by orbit setup; do not edit"

// maxModuleDepth is how far below a repository a go.mod is searched; the repository root is depth 0.
const maxModuleDepth = 4

// skipModuleDirs are directory names never searched for go.mod files, nor is any dot-directory.
var skipModuleDirs = map[string]bool{"node_modules": true, "vendor": true, "testdata": true}

// goModule is one Go module found under a selected repository.
type goModule struct {
	dir     string // slash path relative to the workspace root
	version string // the go directive, empty when the go.mod has none
}

// GoWork returns the go.work file that lists moduleDirs, slash paths relative to the workspace root.
// Directories are sorted and written as ./<dir>; goVersion is the go line.
func GoWork(goVersion string, moduleDirs []string) string {
	dirs := make([]string, 0, len(moduleDirs))
	for _, d := range moduleDirs {
		dirs = append(dirs, "./"+path.Clean(filepath.ToSlash(d)))
	}
	sort.Strings(dirs)

	var b strings.Builder
	b.WriteString(goWorkMarker + "\n")
	b.WriteString("go " + goVersion + "\n\n")
	b.WriteString("use (\n")
	for _, d := range dirs {
		b.WriteString("\t" + d + "\n")
	}
	b.WriteString(")\n")
	return b.String()
}

// planGoWork plans the go.work file at key from the Go modules of the selected repositories. With no
// modules, a go.work this part wrote is removed; a hand-made one is only reported.
func planGoWork(s *engine.State, key string) (engine.Plan, error) {
	selected, err := s.Selected()
	if err != nil {
		return engine.Plan{}, err
	}
	var mods []goModule
	for _, repo := range selected {
		if err := walkModules(s, filepath.Join(s.Root, filepath.FromSlash(repo.Path)), 0, &mods); err != nil {
			return engine.Plan{}, err
		}
	}

	dest := filepath.Join(s.Root, filepath.FromSlash(key))
	existing, err := s.FS.ReadFile(dest)
	exists := err == nil
	if err != nil && !isMissing(err) {
		return engine.Plan{}, clierr.Wrap(err, clierr.Failed("cannot read "+dest))
	}
	marked := exists && strings.SplitN(string(existing), "\n", 2)[0] == goWorkMarker

	var plan engine.Plan
	if len(mods) == 0 {
		if marked {
			plan.Actions = append(plan.Actions, engine.Action{
				Part:    partName,
				Subject: key,
				Summary: "Remove " + key,
				Do: func(context.Context) error {
					if err := s.FS.Remove(dest); err != nil {
						return clierr.Wrap(err, clierr.Failed("cannot remove "+dest))
					}
					return nil
				},
			})
		}
		return plan, nil
	}

	if exists && !marked {
		plan.Findings = append(plan.Findings, engine.Finding{
			Part:     partName,
			Subject:  key,
			Message:  key + " is hand-made; delete it to let orbit setup manage it",
			Severity: engine.SeverityWarn,
		})
		return plan, nil
	}

	goVersion, dirs := highestGo(mods)
	if goVersion == "" {
		plan.Findings = append(plan.Findings, engine.Finding{
			Part:     partName,
			Subject:  key,
			Message:  key + " not written: no selected Go module declares a go version",
			Severity: engine.SeverityWarn,
		})
		return plan, nil
	}
	want := GoWork(goVersion, dirs)
	if exists && string(existing) == want {
		return plan, nil
	}
	plan.Actions = append(plan.Actions, engine.Action{
		Part:    partName,
		Subject: key,
		Summary: "Write " + key,
		Do: func(context.Context) error {
			if err := s.FS.WriteFile(dest, []byte(want), 0o644); err != nil {
				return clierr.Wrap(err, clierr.Failed("cannot write "+dest))
			}
			return nil
		},
	})
	return plan, nil
}

// walkModules appends every go.mod at dir or below it, up to maxModuleDepth levels down. Symlinked
// directories are not followed, and skipped directories are not entered.
func walkModules(s *engine.State, dir string, depth int, out *[]goModule) error {
	data, err := s.FS.ReadFile(filepath.Join(dir, "go.mod"))
	switch {
	case err == nil:
		rel, err := filepath.Rel(s.Root, dir)
		if err != nil {
			return clierr.Wrap(err, clierr.Failed("cannot relate "+dir+" to "+s.Root))
		}
		*out = append(*out, goModule{dir: filepath.ToSlash(rel), version: goDirective(data)})
	case isMissing(err):
	default:
		return clierr.Wrap(err, clierr.Failed("cannot read "+dir+"/go.mod"))
	}
	if depth == maxModuleDepth {
		return nil
	}
	entries, err := s.FS.ReadDir(dir)
	if isMissing(err) {
		return nil
	}
	if err != nil {
		return clierr.Wrap(err, clierr.Failed("cannot read "+dir))
	}
	for _, e := range entries {
		name := e.Name()
		if !e.IsDir() || skipModuleDirs[name] || strings.HasPrefix(name, ".") {
			continue
		}
		if err := walkModules(s, filepath.Join(dir, name), depth+1, out); err != nil {
			return err
		}
	}
	return nil
}

// goDirective returns the version of the first go line of a go.mod, or "" when there is none.
func goDirective(gomod []byte) string {
	for _, line := range strings.Split(string(gomod), "\n") {
		fields := strings.Fields(line)
		if len(fields) >= 2 && fields[0] == "go" {
			return fields[1]
		}
	}
	return ""
}

// highestGo returns the highest go directive among mods and the directories of all mods.
func highestGo(mods []goModule) (string, []string) {
	var highest string
	dirs := make([]string, 0, len(mods))
	for _, m := range mods {
		dirs = append(dirs, m.dir)
		if m.version != "" && (highest == "" || compareGo(m.version, highest) > 0) {
			highest = m.version
		}
	}
	return highest, dirs
}

// compareGo compares two go versions numerically by dotted part: 1.27.4 > 1.27 > 1.9. A missing part
// counts as zero, and a part's leading digits are its value.
func compareGo(a, b string) int {
	pa, pb := strings.Split(a, "."), strings.Split(b, ".")
	for i := 0; i < len(pa) || i < len(pb); i++ {
		x, y := goPart(pa, i), goPart(pb, i)
		switch {
		case x < y:
			return -1
		case x > y:
			return 1
		}
	}
	return 0
}

// goPart returns the leading digits of parts[i], or 0 when there is no such part.
func goPart(parts []string, i int) int {
	if i >= len(parts) {
		return 0
	}
	digits := parts[i]
	for j, r := range digits {
		if r < '0' || r > '9' {
			digits = digits[:j]
			break
		}
	}
	n, err := strconv.Atoi(digits)
	if err != nil {
		return 0
	}
	return n
}
