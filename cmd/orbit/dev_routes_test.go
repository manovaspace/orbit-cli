const devRoutesHeader = "# Generated by orbit dev routes from handbook/agents/workspace/ports.yaml; do not edit.\n"

func TestDevRoutesDefaultPrintsCaddyfile(t *testing.T) {
	isolateDevConfig(t, "")
	code, out, errOut := runDev(t, "dev", "routes", "--root", writeDevTestRoot(t))
	if code != 0 {
		t.Fatalf("exit = %d, stderr: %s", code, errOut)
	}
	want := devRoutesHeader + "\nhttp://gateway.localhost {\n\treverse_proxy 127.0.0.1:10001\n}\n"
	if out != want {
		t.Fatalf("Caddyfile =\n%q\nwant\n%q", out, want)
	}
}

func TestDevRoutesWriteCreatesFile(t *testing.T) {
	isolateDevConfig(t, "")
	target := filepath.Join(t.TempDir(), "nested", "dir", "Caddyfile")
	code, out, errOut := runDev(t, "dev", "routes", "--root", writeDevTestRoot(t), "--write", target)
	if code != 0 {
		t.Fatalf("exit = %d, stderr: %s", code, errOut)
	}
	if strings.TrimSpace(out) != target {
		t.Errorf("stdout = %q, want the written path %q", out, target)
	}
	data, err := os.ReadFile(target)
	if err != nil {
		t.Fatalf("read written file: %v", err)
	}
	if !strings.Contains(string(data), "http://gateway.localhost {\n\treverse_proxy 127.0.0.1:10001\n}\n") {
		t.Errorf("written file = %q", data)
	}
	info, err := os.Stat(target)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode().Perm() != 0o644 {
		t.Errorf("mode = %o, want 0644", info.Mode().Perm())
	}
}

func TestDevRoutesListTable(t *testing.T) {
	isolateDevConfig(t, "")
	code, out, errOut := runDev(t, "dev", "routes", "--root", writeDevTestRoot(t), "--list")
	if code != 0 {
		t.Fatalf("exit = %d, stderr: %s", code, errOut)
	}
	for _, want := range []string{"NAME", "URL", "PORT", "SERVICE", "http://gateway.localhost", "10001", "orbit-api-gateway"} {
		if !strings.Contains(out, want) {
			t.Errorf("list missing %q:\n%s", want, out)
		}
	}
}

func TestDevRoutesJSONList(t *testing.T) {
	isolateDevConfig(t, "")
	code, out, errOut := runDev(t, "dev", "routes", "--root", writeDevTestRoot(t), "--json")
	if code != 0 {
		t.Fatalf("exit = %d, stderr: %s", code, errOut)
	}
	env := requireEnvelope(t, bytes.NewBufferString(out))
	var routes []map[string]any
	if err := json.Unmarshal(env.Data, &routes); err != nil {
		t.Fatalf("routes data is not a list: %v\n%s", err, out)
	}
	if len(routes) != 1 || routes[0]["url"] != "http://gateway.localhost" || routes[0]["service"] != "orbit-api-gateway" {
		t.Errorf("routes = %v", routes)
	}
}

func TestDevRoutesMissingRegistryIsUnverified(t *testing.T) {
	isolateDevConfig(t, "")
	code, _, errOut := runDev(t, "dev", "routes", "--root", t.TempDir())
	if code != clierr.ExitUnverified {
		t.Fatalf("exit = %d, want %d; stderr: %s", code, clierr.ExitUnverified, errOut)
	}
}

func TestDevRoutesWriteWithListIsUsageError(t *testing.T) {
	isolateDevConfig(t, "")
	code, _, errOut := runDev(t, "dev", "routes", "--root", writeDevTestRoot(t), "--write", filepath.Join(t.TempDir(), "C"), "--list")
	if code != clierr.ExitUsage {
		t.Fatalf("exit = %d, want usage; stderr: %s", code, errOut)
	}
}

// isolateDevConfig points ORBIT_CONFIG at a temp file holding content.
func isolateDevConfig(t *testing.T, content string) {
	t.Helper()
	path := filepath.Join(t.TempDir(), "config.yaml")
	if content != "" {
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	t.Setenv("ORBIT_CONFIG", path)
}

// devTestRegistry is a workspace registry with two shared services, one shared
// exception, and one mac service that the route output must not list as shared.
const devTestRegistry = `version: 1
base: 10000
block_size: 50
fixed_slots: 10
projects:
  - { id: 0, name: orbit-platform }
services:
  - { port: 10000, project: orbit-platform, name: postgres, proto: tcp, runs: shared, repos: [orbit/orbit-infra] }
  - { port: 10006, project: orbit-platform, name: nats, proto: tcp, runs: shared, bind: 10.0.0.1, repos: [orbit/orbit-infra] }
  - { port: 10001, project: orbit-platform, name: orbit-api-gateway, proto: http, runs: mac, repos: [orbit/orbit-api-gateway], localhost: gateway }
exceptions:
  - { port: 10334, name: redis, runs: shared, repos: [orbit/orbit-infra], reason: "test", until: "test" }
`

// writeDevTestRoot writes a workspace root holding handbook/agents/workspace/ports.yaml.
func writeDevTestRoot(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	dir := filepath.Join(root, "handbook", "agents", "workspace")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "ports.yaml"), []byte(devTestRegistry), 0o644); err != nil {
		t.Fatal(err)
	}
	return root
}

// runDev runs the CLI entry point with args and returns the exit code, stdout and stderr.
func runDev(t *testing.T, args ...string) (int, string, string) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	code := run(args, &stdout, &stderr)
	return code, stdout.String(), stderr.String()
}
