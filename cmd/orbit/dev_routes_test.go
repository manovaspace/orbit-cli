const devRoutesHeader = "# Generated by orbit dev routes from handbook/agents/workspace/ports.yaml; do not edit.\n"

func TestDevRoutesDefaultPrintsCaddyfile(t *testing.T) {
	isolateDevConfig(t, "")
	code, out, errOut := runDev(t, "dev", "routes", "--root", writeDevTestRoot(t))
	if code != 0 {
		t.Fatalf("exit = %d, stderr: %s", code, errOut)
	}
	want := devRoutesHeader + "\nhttp://gateway.localhost {\n\treverse_proxy 127.0.0.1:10001\n}\n"
	if out != want {
		t.Fatalf("Caddyfile =\n%q\nwant\n%q", out, want)
	}
}

func TestDevRoutesWriteCreatesFile(t *testing.T) {
	isolateDevConfig(t, "")
	target := filepath.Join(t.TempDir(), "nested", "dir", "Caddyfile")
	code, out, errOut := runDev(t, "dev", "routes", "--root", writeDevTestRoot(t), "--write", target)
	if code != 0 {
		t.Fatalf("exit = %d, stderr: %s", code, errOut)
	}
	if strings.TrimSpace(out) != target {
		t.Errorf("stdout = %q, want the written path %q", out, target)
	}
	data, err := os.ReadFile(target)
	if err != nil {
		t.Fatalf("read written file: %v", err)
	}
	if !strings.Contains(string(data), "http://gateway.localhost {\n\treverse_proxy 127.0.0.1:10001\n}\n") {
		t.Errorf("written file = %q", data)
	}
	info, err := os.Stat(target)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode().Perm() != 0o644 {
		t.Errorf("mode = %o, want 0644", info.Mode().Perm())
	}
}

func TestDevRoutesListTable(t *testing.T) {
	isolateDevConfig(t, "")
	code, out, errOut := runDev(t, "dev", "routes", "--root", writeDevTestRoot(t), "--list")
	if code != 0 {
		t.Fatalf("exit = %d, stderr: %s", code, errOut)
	}
	for _, want := range []string{"NAME", "URL", "PORT", "SERVICE", "http://gateway.localhost", "10001", "orbit-api-gateway"} {
		if !strings.Contains(out, want) {
			t.Errorf("list missing %q:\n%s", want, out)
		}
	}
}

func TestDevRoutesJSONList(t *testing.T) {
	isolateDevConfig(t, "")
	code, out, errOut := runDev(t, "dev", "routes", "--root", writeDevTestRoot(t), "--json")
	if code != 0 {
		t.Fatalf("exit = %d, stderr: %s", code, errOut)
	}
	env := requireEnvelope(t, bytes.NewBufferString(out))
	var routes []map[string]any
	if err := json.Unmarshal(env.Data, &routes); err != nil {
		t.Fatalf("routes data is not a list: %v\n%s", err, out)
	}
	if len(routes) != 1 || routes[0]["url"] != "http://gateway.localhost" || routes[0]["service"] != "orbit-api-gateway" {
		t.Errorf("routes = %v", routes)
	}
}

